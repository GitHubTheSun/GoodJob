def tr(lang: str, key: str, **kwargs: object) -> str:
    table = STRINGS.get(lang) or STRINGS["zh"]
    text = table.get(key) or STRINGS["zh"].get(key) or key
    if not kwargs:
        return text
    return text.format(**kwargs)


